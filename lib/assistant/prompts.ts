/**
 * اتصال بخش‌های مختلف پرامپت
 *
 * بخش‌های خالی حذف می‌شوند تا پرامپت نهایی
 * مرتب و کم‌حجم باقی بماند.
 */
function joinPromptSections(
  sections:
    Array<
      string |
      null |
      undefined |
      false
    >
) {
  return sections
    .filter(
      (
        section
      ):
        section is string =>
        typeof section ===
          "string" &&
        section.trim().length >
          0
    )
    .map(
      section =>
        section.trim()
    )
    .join(
      "\n\n"
    );
}


